int waitpid(int pid) {
	struct proc* p = get_proc_from_pid(pid);

	if(p == 0 || p->parent != myproc()){
		return -1;
	}

	acquire(&wait_lock);
    sleep(myproc(), &wait_lock);
    release(&wait_lock);

	return 0;
}

// Custom function helping getting the struct proc from a PID
struct proc* get_proc_from_pid(int pid)
{
  struct proc *p;

  for(p = proc; p < &proc[NPROC]; p++){
    if(p->pid == pid){
      return p;
    }
  }
  return 0;
}

// Custom function that get a process from it's index in the proc[] array
struct proc* get_proc_from_index(int index) {
  if (index < 0 || index >= NPROC) {
    return 0;
  }

  struct proc *p = &proc[index];
  if (p->pid == 0) {
    return 0;
  }

  return p;
}

void update_vdeadline(struct proc *p) {
  if (p->state != RUNNABLE && p->state != RUNNING) {
    p->is_eligible = 0;
    return;
  }
  const int base_time_slice = 5;
  p->vdeadline = p->vruntime + base_time_slice * WEIGHT_OF_NICE_20 / weight[p->nice];
}

int update_is_eligible(struct proc *p) {
  long sum_vi = 0;
  long sum_wi = 0;
  long v_0 = p->vruntime;

  for (struct proc *q = proc; q < &proc[NPROC]; q++) {
    if ((q->state == RUNNABLE || q->state == RUNNING) && q->vruntime < v_0) {
      v_0 = q->vruntime;
    }
  }

  for (struct proc *q = proc; q < &proc[NPROC]; q++) {
    if (q->state == RUNNABLE || q->state == RUNNING) {
      sum_vi += (q->vruntime - v_0) * weight[q->nice];
      sum_wi += weight[q->nice];
    }
  }

  p->is_eligible = sum_vi >= (p->vruntime - v_0) * sum_wi;
  return p->is_eligible;
}
